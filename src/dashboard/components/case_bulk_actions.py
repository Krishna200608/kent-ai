def export_cases_to_json(cases: List[ClinicalCase]) -> str:
    """Serialize multiple clinical cases into a single structured JSON bundle."""
    bundle = {
        "export_metadata": {
            "system": "Kent-AI Clinical Decision Support",
            "exported_at": datetime.now(timezone.utc).isoformat(),
            "case_count": len(cases),
            "schema_version": "1.0",
        },
        "cases": [c.to_dict() for c in cases],
    }
    return json.dumps(bundle, indent=2)


def export_cases_to_csv(cases: List[ClinicalCase]) -> str:
    """Generate a clean CSV summary roster of clinical cases for audit and research."""
    output = io.StringIO()
    writer = csv.writer(output)

    # Header row
    writer.writerow([
        "Case ID",
        "Patient Name",
        "Age",
        "Sex",
        "Status",
        "Chief Complaint",
        "Dimensions Captured",
        "Total Symptoms",
        "Leading Remedy",
        "Created At",
        "Updated At",
    ])

    for c in cases:
        dims = c.dimensions or {}
        dim_count = sum(1 for v in dims.values() if v)
        total_symptoms = sum(len(v) for v in dims.values() if isinstance(v, list))

        top_remedy = "—"
        if c.report_data and isinstance(c.report_data, dict):
            rems = c.report_data.get("ranked_remedies", [])
            if rems and isinstance(rems, list):
                top_remedy = f"{rems[0].get('abbreviation')} ({rems[0].get('score', 0):.2f})"

        writer.writerow([
            c.case_id,
            c.patient_name,
            c.patient_age or "",
            c.patient_sex or "",
            c.status,
            c.chief_complaint or "",
            dim_count,
            total_symptoms,
            top_remedy,
            c.created_at,
            c.updated_at,
        ])

    return output.getvalue()


def export_cases_to_markdown(cases: List[ClinicalCase]) -> str:
    """Generate a structured clinical consultation digest in Markdown."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = [
        "# Kent-AI Clinical Consultations Digest",
        f"- **Exported At**: {now_str}",
        f"- **Total Cases**: {len(cases)}",
        "\n---\n",
        "## Summary Roster\n",
        "| Case ID | Patient | Demographics | Status | Dimensions | Leading Remedy |",
        "|---|---|---|---|---|---|",
    ]

    for c in cases:
        demo = f"{c.patient_age or '?'}{c.patient_sex[0] if c.patient_sex else ''}"
        dims_count = c.filled_dimensions_count
        top_rem = "—"
        if c.report_data and isinstance(c.report_data, dict):
            rems = c.report_data.get("ranked_remedies", [])
            if rems:
                top_rem = f"{rems[0].get('abbreviation')} ({rems[0].get('score', 0):.2f})"
        lines.append(f"| `{c.case_id}` | {c.patient_name} | {demo} | {c.status.upper()} | {dims_count}/7 | {top_rem} |")

    lines.append("\n---\n")
    lines.append("## Detailed Case Notes\n")

    for idx, c in enumerate(cases, 1):
        lines.append(f"### {idx}. Case `{c.case_id}` — {c.patient_name}")
        lines.append(f"- **Chief Complaint**: {c.chief_complaint or 'None recorded'}")
        lines.append(f"- **Status**: {c.status.upper()} &middot; **Updated**: {c.updated_at}")
        if c.clinical_summary:
            lines.append(f"- **Clinical Summary**: {c.clinical_summary}")

        lines.append("- **Symptom Totality Breakdown**:")
        if c.dimensions:
            for k, items in c.dimensions.items():
                if items:
                    lines.append(f"  - **{k.title()}**: {', '.join(items)}")
        else:
            lines.append("  - *(No symptom dimensions recorded)*")

        lines.append("")

    lines.append("---\n*Generated by Kent-AI Clinical Decision Support Case Library.*")
    return "\n".join(lines)


def render_bulk_action_bar(
    selected_ids: List[str],
    current_case: ClinicalCase,
) -> None:
    """Render comprehensive bulk operations toolbar when 1 or more cases are selected."""
    if not selected_ids:
        return

    count = len(selected_ids)
    now_stamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    st.html(
        f"""
        <div class="stGlassCard" style="padding: 12px 18px; margin-bottom: 16px; border: 1px solid rgba(16, 185, 129, 0.4); background: rgba(16, 185, 129, 0.06);">
            <div style="display: flex; justify-content: space-between; align-items: center; flex-wrap: wrap; gap: 8px;">
                <div style="display: flex; align-items: center; gap: 8px;">
                    {get_icon('checklist', size=20, color='#10B981')}
                    <span style="font-weight: 700; font-size: 14.5px; color: #F3F4F6;">
                        Bulk Actions: <span style="color: #10B981;">{count}</span> Case{'s' if count > 1 else ''} Selected
                    </span>
                </div>
                <div style="font-size: 12px; color: #9CA3AF;">
                    Select operations below to apply to all {count} consultations
                </div>
            </div>
        </div>
        """
    )

    col_del, col_exp_json, col_exp_csv, col_exp_md, col_status, col_clear = st.columns(
        [1.3, 1.3, 1.3, 1.3, 1.3, 1.1],
        vertical_alignment="center",
    )

    # 1. Bulk Delete with Popover Confirmation
    with col_del:
        with st.popover(f"Delete ({count})", width="stretch", help="Permanently delete selected cases"):
            st.markdown(f"##### Delete {count} Consultation{'s' if count > 1 else ''}?")
            st.markdown(
                f"<div style='font-size: 12px; color: #EF4444; margin-bottom: 10px;'>"
                f"Permanently remove <b>{count}</b> selected case(s) from SQLite storage. This cannot be undone."
                f"</div>",
                unsafe_allow_html=True,
            )
            confirm_box = st.checkbox("Yes, I understand and want to delete", key="bulk_delete_confirm_check")
            if st.button(
                f"Confirm Delete ({count})",
                type="primary",
                disabled=not confirm_box,
                width="stretch",
                key="btn_bulk_delete_execute",
            ):
                deleted_count = delete_cases(selected_ids)

                # Active case guard: if active case was among deleted, reset to a fresh blank case
                if current_case.case_id in selected_ids:
                    new_id = generate_case_id()
                    fresh_case = ClinicalCase(case_id=new_id)
                    st.session_state.current_case = fresh_case
                    if "dialogue_manager" in st.session_state:
                        dm = st.session_state.dialogue_manager
                        dm.reset()
                        dm.resume_from_case(fresh_case)
                    st.session_state.current_report = None
                    st.session_state.workspace_step = 1

                # Clean up session state checkbox keys
                for cid in selected_ids:
                    st.session_state.pop(f"case_select_{cid}", None)

                st.toast(f"Permanently deleted {deleted_count} consultation(s).")
                st.rerun()

    # Pre-fetch selected cases for exports
    loaded_cases: List[ClinicalCase] = []
    if count <= 200:
        loaded_cases = get_cases(selected_ids)

    # 2. Bulk Export JSON Bundle
    with col_exp_json:
        if loaded_cases:
            json_bundle = export_cases_to_json(loaded_cases)
            st.download_button(
                f"Export JSON ({count})",
                data=json_bundle,
                file_name=f"kent_cases_{count}_{now_stamp}.json",
                mime="application/json",
                width="stretch",
                key="btn_bulk_export_json",
                help="Export full consultation data as a structured JSON bundle",
            )
        else:
            st.button(f"Export JSON ({count})", disabled=True, width="stretch", key="btn_bulk_export_json_dis")

    # 3. Bulk Export CSV Roster
    with col_exp_csv:
        if loaded_cases:
            csv_roster = export_cases_to_csv(loaded_cases)
            st.download_button(
                f"Export CSV ({count})",
                data=csv_roster,
                file_name=f"kent_cases_roster_{count}_{now_stamp}.csv",
                mime="text/csv",
                width="stretch",
                key="btn_bulk_export_csv",
                help="Download tabular CSV spreadsheet of selected cases for audits or statistics",
            )
        else:
            st.button(f"Export CSV ({count})", disabled=True, width="stretch", key="btn_bulk_export_csv_dis")

    # 4. Bulk Export Markdown Digest
    with col_exp_md:
        if loaded_cases:
            md_digest = export_cases_to_markdown(loaded_cases)
            st.download_button(
                "Export Digest (.md)",
                data=md_digest,
                file_name=f"kent_cases_digest_{count}_{now_stamp}.md",
                mime="text/markdown",
                width="stretch",
                key="btn_bulk_export_md",
                help="Export Markdown consultation summary digest with symptom totality breakdown",
            )
        else:
            st.button("Export Digest (.md)", disabled=True, width="stretch", key="btn_bulk_export_md_dis")

    # 5. Bulk Status Change
    with col_status:
        with st.popover("Set Status", width="stretch", help="Update clinical stage status for selected cases"):
            st.markdown(f"##### Update Status ({count} Cases)")
            target_status_label = st.selectbox(
                "New Clinical Status:",
                options=["In Review", "Analyzed", "Draft", "Archived"],
                key="bulk_status_target_select",
            )
            if st.button("Apply Status", type="primary", width="stretch", key="btn_bulk_status_apply"):
                norm_status = target_status_label.lower().replace(" ", "_")
                updated_count = update_cases_status(selected_ids, norm_status)
                st.toast(f"Updated status to '{target_status_label}' for {updated_count} case(s).")
                st.rerun()

    # 6. Clear Selection
    with col_clear:
        if st.button("Clear", width="stretch", key="btn_bulk_clear_selection", help="Deselect all cases"):
            for cid in selected_ids:
                st.session_state[f"case_select_{cid}"] = False
            st.rerun()

    st.markdown("<div style='margin-bottom: 12px;'></div>", unsafe_allow_html=True)


